from __future__ import annotations

"""Routes exposing trading agent functionality."""

import logging
import os
from dataclasses import asdict
from typing import List

from fastapi import APIRouter
from pydantic import BaseModel

from backend import alerts as alert_utils
from backend.agent import trading_agent
from backend.agent.models import TradingSignal
from backend.common.alerts import publish_alert
from backend.config import config
from backend.logging_setup import sanitise_log_value
from backend.utils.telegram_utils import redact_token, send_message

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/trading-agent", tags=["trading-agent"])


class TradingAgentSettings(BaseModel):
    """Public, non-secret thresholds used to generate trading signals."""

    rsi_buy: float | None
    rsi_sell: float | None
    rsi_window: int
    ma_short_window: int
    ma_long_window: int
    pe_max: float | None
    de_max: float | None
    min_sharpe: float | None
    max_volatility: float | None


@router.get("/settings", response_model=TradingAgentSettings)
async def settings() -> TradingAgentSettings:
    """Return the active signal thresholds without exposing server config."""

    return TradingAgentSettings.model_validate(asdict(trading_agent.load_strategy_config()))


@router.get(
    "/signals",
    response_model=List[TradingSignal],
    response_model_exclude_none=True,
)
async def signals(notify_email: bool = False, notify_telegram: bool = False) -> List[TradingSignal]:
    """Return trade signals generated by the trading agent.

    Each signal contains the ticker symbol, a ``BUY`` or ``SELL`` action and
    a human-readable reason describing why the signal was generated.
    Optional email and/or Telegram notifications can be triggered by setting
    the corresponding query parameters to ``true``.
    """

    raw_signals = trading_agent.run(notify=False)

    if raw_signals:
        messages = [
            trading_agent.format_signal_message(s["action"], s["ticker"], s["reason"], s.get("checks_skipped"))
            for s in raw_signals
        ]
        text = "\n".join(messages)
        if notify_email:
            try:
                publish_alert({"message": text})
                alert_utils.send_push_notification(text)
            except RuntimeError:
                logger.info("SNS topic ARN not configured; skipping email publish")
        if (
            notify_telegram
            and os.getenv("TELEGRAM_BOT_TOKEN")
            and os.getenv("TELEGRAM_CHAT_ID")
            and config.app_env != "aws"
        ):
            try:
                send_message(text)
            except Exception as exc:  # pragma: no cover - network errors
                # redact_token() only strips the bot token; the exception message
                # can otherwise carry embedded newlines from a signal's ticker or
                # reason text (composed into `text` above), so it also needs
                # sanitise_log_value's CRLF stripping (#5260).
                logger.warning("Telegram send failed: %s", sanitise_log_value(redact_token(str(exc))))

    return [TradingSignal.model_validate(sig) for sig in raw_signals]
